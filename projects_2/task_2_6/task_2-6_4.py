print("=" * 60)
print("\nСтоит витязь перед камнем вещим, а на камне том надпись:")
print("\n\"Налево пойдёшь — коня потеряешь, себя спасёшь.")
print("Направо пойдёшь — себя потеряешь, коня спасёшь.")
print("Прямо пойдёшь — и себя, и коня потеряешь.\"")
print("А есть ещё путь четвёртый — назад воротиться...")
print("\n" + "=" * 60)

# Выбор пути витязем
choice = input("\nКуда направишься, витязь? (налево/направо/прямо/назад): ").strip().lower()

print("\n" + "-" * 40)

# Анализ выбора и последствия с использованием if/elif/else и or
if choice == "налево" or choice == "левый" or choice == "лево":
    print("Поехал витязь налево...")
    print("Попал в тёмный лес, напали разбойники.")
    print("Бился витязь храбро, коня верного потерял в бою,")
    print("но сам ушёл от погони и спасся.")
    print("\nИТОГ: Конь потерян, витязь жив.")

elif choice == "направо" or choice == "правый" or choice == "право":
    print("Поехал витязь направо...")
    print("Встретил Змея Горыныча трёхглавого.")
    print("Битва была страшная, витязь пал в бою,")
    print("но конь его верный унёсся в чисто поле и спасся.")
    print("\nИТОГ: Витязь погиб, конь спасён.")

elif choice == "прямо" or choice == "прямой":
    print("Поехал витязь прямо...")
    print("Попал в болото зыбучее, трясину непролазную.")
    print("Ни конь, ни витязь выбраться не смогли.")
    print("\nИТОГ: И витязь, и конь сгинули в болоте.")

elif choice == "назад" or choice == "обратно" or choice == "домой":
    print("Повернул витязь коня назад...")
    print("Воротился в родные края, к отцу с матерью.")
    print("Женился, деток народил, хозяйство поднял.")
    print("Слава о нём по земле русской пошла добрая.")
    print("\nИТОГ: Жив-здоров витязь, и конь при нём.")

else:
    print("Не понял витязь надписи на камне...")
    print("Стоит и дальше, размышляет...")
    other_choice = input("\nМожет, ещё раз выберешь? (да/нет): ").strip().lower()
    
    if other_choice == "да" or other_choice == "yes" or other_choice == "ага":
        print("\nЗапусти программу заново, витязь, и сделай правильный выбор!")
    else:
        print("\nТак и остался витязь стоять у камня на все времена...")
        print("А люди мимо ходят, картины пишут, легенды слагают.")

print("\n" + "=" * 60)
print("БЫЛИНЕ КОНЕЦ, А КТО СЛУШАЛ — МОЛОДЕЦ!")
print("=" * 60)