 
N = int(input("Введите количество чисел N: "))

# Проверка на корректность ввода
if N < 1:
    print("Ошибка: N должно быть ≥ 1!")
else:
    # Начальные значения
    S = 0
    i = 1
    
    # Цикл для вычисления суммы квадратов
    while i <= N:
        S = S + i * i
        i = i + 1
    
    # Вывод результата
    print(f"Сумма квадратов первых {N} чисел: 1² + 2² + ... + {N}² = {S}")