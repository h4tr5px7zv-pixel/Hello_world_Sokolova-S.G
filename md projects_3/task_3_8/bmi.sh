#!/bin/bash
# Скрипт для расчета индекса массы тела (BMI)

# Запрашиваем массу тела
echo -n "Введите массу тела (в кг): "
read weight
 
# Запрашиваем рост
echo -n "Введите рост (в метрах, например 1.75): "
read height

# Вычисляем приблизительный BMI (умножаем на 100 и делим целочисленно)
# BMI = вес / (рост * рост)
# Умножаем на 100 чтобы сохранить точность до сотых
bmi=$(( (weight) / (height * height) ))

# Выводим результат (целая часть)
echo "Ваш индекс массы тела: $((bmi / 100))"


