
#!/bin/bash
# Скрипт с функцией проверки прав суперпользователя

# Определяем функцию check_root
check_root() {
    if [ $EUID -ne 0 ]; then
        echo "Ошибка: Скрипт должен быть запущен от имени суперпользователя (root)."
        echo "Текущий UID: $EUID"
        echo "Используйте: sudo ./check_root.sh"
        exit 1
    fi
}

# Вызываем функцию проверки
check_root

# Основная часть скрипта (выполняется только если check_root пройдена)
echo "Скрипт запущен от имени суперпользователя."
echo "UID: $EUID"
echo "Выполнение основной логики скрипта..."

# Здесь может быть любой код, требующий прав root
echo "Текущая дата: $(date)"
echo "Системная информация:"
uname -a

exit 0

