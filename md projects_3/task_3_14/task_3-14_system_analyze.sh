#!/bin/bash
# Скрипт для анализа использования дискового пространства

echo "========================================="
echo "        АНАЛИЗ ДИСКОВОЙ СИСТЕМЫ"
echo "========================================="
echo ""

# Выводим заголовок таблицы
printf "%-20s %-10s %s\n" "Файловая система" "Использовано" "Статус"
printf "%-20s %-10s %s\n" "--------------------" "----------" "------"

# Анализируем вывод команды df -h с помощью awk
df -h | awk 'NR>1 {
    fs=$1
    use=$5
    
    # Убираем символ % из значения
    gsub(/%/, "", use)
    
    # Определяем статус
    if (use > 90) {
        status="⚠️ КРИТИЧЕСКИ!"
    } else if (use > 80) {
        status="⚠️ Внимание"
    } else {
        status="✓ OK"
    }
    
    # Выводим результат
    printf "%-20s %-10s %s\n", fs, $5, status
}'

echo ""
echo "========================================="
echo "Легенда:"
echo "  ✓ OK - нормальное использование (<80%)"
echo "  ⚠️ Внимание - повышенное использование (80-90%)"
echo "  ⚠️ КРИТИЧЕСКИ! - критическое использование (>90%)"
echo "========================================="

