#!/bin/bash
# Скрипт для анализа данных из файла data.csv

echo "========================================="
echo "        АНАЛИЗ ТОВАРОВ ИЗ CSV"
echo "========================================="
echo ""

echo "Исходные данные:"
echo "----------------"
cat data.csv
echo ""

echo "НАЗВАНИЯ ТОВАРОВ:"
echo "-----------------"
cut -d',' -f2 data.csv
echo ""

echo "ТОВАРЫ ДОРОЖЕ 20:"
echo "-----------------"
awk -F',' '$3 > 20 {print $0}' data.csv
echo ""

echo "ОБЩАЯ СТОИМОСТЬ:"
echo "----------------"
total=$(awk -F',' '{sum += $3} END {print sum}' data.csv)
echo "Сумма всех товаров: $total"
echo "========================================="

