#!/bin/bash
# Скрипт для поиска строки текущего пользователя в файле /etc/passwd

echo "Поиск информации о пользователе $USER в файле /etc/passwd..."
echo ""

# Используем grep для поиска строки с именем текущего пользователя
grep "^$USER:" /etc/passwd

# Проверяем результат выполнения grep
if [ $? -eq 0 ]; then
    echo ""
    echo "Пользователь $USER найден в системе."
else
    echo ""
    echo "Пользователь $USER не найден в системе."
fi

