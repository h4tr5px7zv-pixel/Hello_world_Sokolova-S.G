#!/bin/bash
# Скрипт для поиска всех файлов с расширением .conf в директории /etc
# Поиск игнорирует регистр (находит .conf, .CONF, .Conf и т.д.)

echo "Поиск файлов с расширением .conf в директории /etc (регистронезависимый)..."
echo ""

# Используем ls -l /etc и grep с ключом -i для игнорирования регистра
ls -l /etc | grep -i "\.conf"

# Подсчитываем количество найденных файлов
count=$(ls -l /etc | grep -i "\.conf" | wc -l)
echo ""
echo "Всего найдено файлов: $count"

