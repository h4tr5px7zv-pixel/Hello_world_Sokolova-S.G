#!/bin/bash
# Скрипт для вывода нечетных чисел от 1 до 20 с остановкой на 15

echo "Нечетные числа от 1 до 20 (до встречи с 15):"

# Перебираем числа от 1 до 20
for i in {1..20}; do
    
    # Проверка на число 15 - остановка
    if [ $i -eq 15 ]; then
        echo "Встретилось число 15. Останавливаем работу."
        break
    fi
    
    # Проверка на четность - пропускаем четные числа
    if [ $((i % 2)) -eq 0 ]; then
        continue
    fi
    
    # Выводим нечетные числа
    echo $i
    
done

echo "Скрипт завершен."

