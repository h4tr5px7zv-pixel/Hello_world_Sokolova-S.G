#!/bin/bash
# Скрипт для подсчета нуклеотидов A, T, G, C в FASTA файлах

echo "Подсчет нуклеотидов в FASTA файлах..."
echo ""

# Выводим заголовок таблицы
printf "%-20s %-10s %-10s %-10s %-10s\n" "Файл" "A" "T" "G" "C"
printf "%-20s %-10s %-10s %-10s %-10s\n" "--------------------" "----------" "----------" "----------" "----------"

# Перебираем все файлы с расширением .fasta в текущей папке
for file in *.fasta; do
    
    # Проверяем, что файл существует (на случай, если нет ни одного .fasta файла)
    if [ ! -f "$file" ]; then
        echo "FASTA файлы не найдены в текущей директории"
        exit 1
    fi
    
    # Пропускаем пустые файлы (размер 0 байт)
    if [ ! -s "$file" ]; then
        continue
    fi
    
    # Получаем последовательность ДНК (исключаем заголовки, начинающиеся с >)
    # Объединяем все строки в одну для подсчета
    sequence=$(grep -v "^>" "$file" | tr -d '\n' | tr -d ' ')
    
    # Подсчитываем количество каждого нуклеотида
    count_A=$(echo "$sequence" | grep -o "A" | wc -l)
    count_T=$(echo "$sequence" | grep -o "T" | wc -l)
    count_G=$(echo "$sequence" | grep -o "G" | wc -l)
    count_C=$(echo "$sequence" | grep -o "C" | wc -l)
    
    # Выводим результаты для текущего файла
    printf "%-20s %-10s %-10s %-10s %-10s\n" "$file" "$count_A" "$count_T" "$count_G" "$count_C"
    
done

echo ""
echo "Подсчет завершен."

